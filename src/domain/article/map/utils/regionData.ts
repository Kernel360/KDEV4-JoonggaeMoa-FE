// 법정동코드 패턴 체크 함수
export const isSidoLevel = (cortarNo: string): boolean => {
    return cortarNo.endsWith('00000000');
};

export const isSigunguLevel = (cortarNo: string): boolean => {
    return cortarNo.endsWith('00000') && !cortarNo.endsWith('00000000');
};

export const isDongLevel = (cortarNo: string): boolean => {
    return !cortarNo.endsWith('00000');
};

// 시/도 목록만 필터링
export const getCityOptions = (): Region[] => {
    return KOREA_REGIONS.filter(region => isSidoLevel(region.cortarNo));
};

// 특정 시/도에 속한 구/군 목록 필터링
export const getDistrictOptions = (selectedCity: string): Region[] => {
    if (!selectedCity) return [];

    // 선택된 시/도 찾기
    const cityRegion = KOREA_REGIONS.find(region =>
        region.cortarName === selectedCity && isSidoLevel(region.cortarNo)
    );

    if (!cityRegion) return [];

    // 시/도 코드 앞 2자리
    const sidoCode = cityRegion.cortarNo.substring(0, 2);

    // 해당 시/도에 속하는 구/군 찾기
    return KOREA_REGIONS.filter(region =>
        region.cortarNo.startsWith(sidoCode) && isSigunguLevel(region.cortarNo)
    );
};

// 특정 구/군에 속한 동/읍/면 목록 필터링
export const getNeighborhoodOptions = (selectedCity: string, selectedDistrict: string): Region[] => {
    if (!selectedCity || !selectedDistrict) return [];

    // 선택된 구/군 찾기
    const districtRegion = KOREA_REGIONS.find(region =>
        region.cortarName === selectedDistrict && isSigunguLevel(region.cortarNo)
    );

    if (!districtRegion) return [];

    // 구/군 코드 앞 5자리
    const sigunguCode = districtRegion.cortarNo.substring(0, 5);

    // 해당 구/군에 속하는 동/읍/면 찾기
    return KOREA_REGIONS.filter(region =>
        region.cortarNo.startsWith(sigunguCode) && isDongLevel(region.cortarNo)
    );
}; 